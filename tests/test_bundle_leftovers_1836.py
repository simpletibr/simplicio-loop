"""#1836 — leftovers of the #1817 change (`simplicio_loop/_bundle/` became a gitignored build
output in PR #1835). Each test pins one leftover so it cannot silently come back.
"""
import ast
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _read(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return f.read()


def _load_precommit_hook():
    spec = importlib.util.spec_from_file_location("precommit_hook_1836",
                                                  os.path.join(REPO, "hooks", "pre-commit.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_dev_extra_ships_wheel_for_the_tests_that_build_wheels():
    with open(os.path.join(REPO, "pyproject.toml"), "rb") as f:
        dev = tomllib.load(f)["project"]["optional-dependencies"]["dev"]
    names = {req.split(";")[0].split(">")[0].split("<")[0].split("=")[0].strip().lower()
             for req in dev}
    assert "wheel" in names, "the dev extra must install `wheel` (wheel-building tests need it)"


def test_bundle_is_gitignored_and_the_precommit_hook_does_not_stage_it():
    assert "simplicio_loop/_bundle/" in _read(".gitignore").splitlines()
    hook = _load_precommit_hook()
    # a gitignored tree cannot be staged; listing it was a no-op left over from the committed mirror
    assert hook.GENERATED_TREES == ["plugin"]


def test_sync_bundle_docstring_describes_the_build_time_generation():
    doc = ast.get_docstring(ast.parse(_read("scripts/sync_bundle.py")))
    assert "gitignored" in doc
    assert "setup.py" in doc
    assert "regenerate automatically on commit" not in doc
    assert "wired into `hooks/pre-commit.py`" not in doc


def _find_key(node, key):
    if isinstance(node, dict):
        if key in node:
            return node[key]
        for v in node.values():
            hit = _find_key(v, key)
            if hit is not None:
                return hit
    elif isinstance(node, list):
        for v in node:
            hit = _find_key(v, key)
            if hit is not None:
                return hit
    return None


def test_project_json_describes_the_bundle_as_generated_not_committed():
    with open(os.path.join(REPO, "simplicio-loop.project.json"), encoding="utf-8") as f:
        pip_bundle = _find_key(json.load(f), "pip_bundle")
    assert pip_bundle, "project.json must still describe the pip bundle"
    assert "gitignored" in pip_bundle, pip_bundle
    assert "byte-idênticos à source" not in pip_bundle, (
        "the bundle is generated at build time, not a committed byte-identical copy: " + pip_bundle)


def test_claims_audit_bundle_parity_materialises_a_missing_bundle_standalone(tmp_path):
    # Standalone run on a fresh checkout: no simplicio_loop/_bundle/ yet. The audit must generate it
    # (as scripts/check.py does) instead of failing with "bundle dir missing".
    root = str(tmp_path / "checkout")
    for name in ("scripts", "hooks", ".claude", "adapters", "packaging", "tests"):
        shutil.copytree(os.path.join(REPO, name), os.path.join(root, name),
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    bundle = os.path.join(root, "simplicio_loop", "_bundle")
    assert not os.path.exists(bundle), "precondition: the copy must start without the bundle"

    r = subprocess.run([sys.executable, os.path.join(root, "scripts", "claims_audit.py"),
                        "--only", "4"], capture_output=True, text=True, cwd=root, timeout=120,
                       stdin=subprocess.DEVNULL)
    assert r.returncode == 0, r.stdout + r.stderr
    assert "[ok] 4 bundle-parity" in r.stdout, r.stdout
    assert os.path.isdir(os.path.join(bundle, "skills"))


def test_plugin_readme_does_not_claim_to_be_generated_by_sync_plugin():
    # plugin/README.md is hand-written: sync_plugin.py never writes it, so no line may say it is generated.
    text = _read("plugin/README.md").lower()
    assert "generated by" not in text
    assert "is generated" not in text
    assert "hand-written" in text
    # sync_plugin.py must indeed not own README.md
    assert "README" not in _read("scripts/sync_plugin.py")
